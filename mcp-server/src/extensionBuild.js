import { createHash } from 'crypto';
import { existsSync, readdirSync, readFileSync } from 'fs';
import { join, relative, sep } from 'path';
import { fileURLToPath } from 'url';

// A content hash of extension/ baked into the service worker's code. Chrome keeps running an unpacked
// extension's old code until its card is reloaded, and the manifest version alone can't show that.
// The npm package ships extension/ inside it; a clone has it next to mcp-server/.
const PACKAGED_EXTENSION_DIR = fileURLToPath(new URL('../extension/', import.meta.url));
export const EXTENSION_DIR = existsSync(PACKAGED_EXTENSION_DIR)
  ? PACKAGED_EXTENSION_DIR
  : fileURLToPath(new URL('../../extension/', import.meta.url));
export const BUILD_INFO_PATH = join(EXTENSION_DIR, 'background', 'buildInfo.js');

const BINARY = /\.(png|jpe?g|gif|ico|webp|woff2?)$/i;

function listFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith('.')) return [];
    const path = join(dir, entry.name);
    return entry.isDirectory() ? listFiles(path) : [path];
  });
}

export function computeExtensionBuildId(dir = EXTENSION_DIR) {
  const hash = createHash('sha256');
  const files = listFiles(dir)
    .filter((path) => path !== join(dir, 'background', 'buildInfo.js'))
    .map((path) => ({ path, name: relative(dir, path).split(sep).join('/') }))
    .sort((a, b) => (a.name < b.name ? -1 : 1));
  for (const { path, name } of files) {
    // Windows checkouts may turn LF into CRLF; hash text files with LF so every OS gets the same ID.
    const content = BINARY.test(name) ? readFileSync(path) : readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
    hash.update(name).update('\0').update(content).update('\0');
  }
  return hash.digest('hex').slice(0, 12);
}

export function renderBuildInfo(buildId) {
  return [
    '// Generated by `npm run build:id` in mcp-server/. Do not edit by hand.',
    '// A hash of the extension files, so the server can tell when Chrome is still running older code.',
    `export const BUILD_ID = '${buildId}';`,
    '',
  ].join('\n');
}

// The build ID in the extension files on disk next to this server, or null when there are none.
export function readExpectedBuildId(path = BUILD_INFO_PATH) {
  if (!existsSync(path)) return null;
  return readFileSync(path, 'utf8').match(/BUILD_ID = '([0-9a-f]+)'/)?.[1] ?? null;
}

export const EXPECTED_BUILD_ID = readExpectedBuildId();

// Returns a warning to show, or null when the running extension matches the files on disk (or there is nothing to compare).
export function extensionBuildWarning(buildId, expected = EXPECTED_BUILD_ID) {
  if (!expected || buildId === expected) return null;
  return `Chrome is running older FileForge extension code than the files in ${EXTENSION_DIR}. Click the reload icon on the FileForge card at chrome://extensions.`;
}
